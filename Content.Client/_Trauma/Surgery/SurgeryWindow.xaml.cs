using Content.Client._Trauma.Choice.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Trauma.Body;
using Content.Shared._Trauma.Common.Body;
using Content.Shared._Trauma.Surgery.Graph;
using Content.Shared.Body;
using Content.Shared.Hands.EntitySystems;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Trauma.Surgery;

[GenerateTypedNameReferences]
public sealed partial class SurgeryWindow : FancyWindow
{
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    private BodySystem _body;
    private SurgeryGraphSystem _graph;
    private SharedHandsSystem _hands;
    private SpriteSystem _sprite;
    private EntityQuery<BodyPartComponent> _partQuery;

    public event Action<NetEntity, ProtoId<SurgeryProcedurePrototype>, int, ProtoId<OrganCategoryPrototype>?>? OnPerformStep;

    private EntityUid _owner;
    private bool _isBody;
    private EntityUid? _part;
    private SurgeryProcedureInstance? _selected;
    private readonly List<EntityUid> _parts = [];
    private readonly List<SurgeryProcedureInstance> _procedures = [];

    public SurgeryWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _body = _ent.System<BodySystem>();
        _graph = _ent.System<SurgeryGraphSystem>();
        _hands = _ent.System<SharedHandsSystem>();
        _sprite = _ent.System<SpriteSystem>();
        _partQuery = _ent.GetEntityQuery<BodyPartComponent>();
        PartsButton.OnPressed += _ => ViewParts();
        SurgeriesButton.OnPressed += _ => { _selected = null; if (_part is { } p) ViewPart(p); };
        StepsButton.OnPressed += _ => { _selected = null; if (_part is { } p) ViewPart(p); };
        View(ViewType.Parts);
    }

    protected override void FrameUpdate(FrameEventArgs args) { base.FrameUpdate(args); Update(); }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
        _isBody = _ent.HasComponent<BodyComponent>(owner);
        Update();
    }

    private string PartName(EntityUid uid) => _ent.GetComponent<MetaDataComponent>(uid).EntityName;

    private string ProcedureName(SurgeryProcedureInstance inst)
    {
        var name = Loc.GetString(_proto.Index(inst.Procedure).Name);
        if (inst.Organ is { } cat && _proto.TryIndex(cat, out var cp))
            name = Loc.GetString("surgery-procedure-organ", ("procedure", name), ("organ", cp.Name));
        return name;
    }

    private bool Deleted(EntityUid uid) => !_ent.TryGetComponent(uid, out MetaDataComponent? c) || c.EntityDeleted;

    private void ViewProcedure(EntityUid part, SurgeryProcedureInstance inst)
    {
        if (!_proto.TryIndex(inst.Procedure, out var proc)) return;
        _part = part; _selected = inst;
        Steps.RemoveAllChildren();
        var netPart = _ent.GetNetEntity(part);
        for (var i = 0; i < proc.Steps.Count; i++)
        {
            var step = proc.Steps[i];
            var btn = new ChoiceControl();
            var msg = new FormattedMessage();
            msg.AddText(Loc.GetString(step.Name));

            var icon = step.Icon;
            if (icon is null && step.Quality is { } quality && _proto.TryIndex(quality, out var qualityProto))
                icon = qualityProto.Icon;
            var texture = icon is null ? null : _sprite.Frame0(icon);

            btn.Set(msg, texture);
            var idx = i;
            btn.Button.OnPressed += _ => OnPerformStep?.Invoke(netPart, inst.Procedure, idx, inst.Organ);
            Steps.AddChild(btn);
        }
        View(ViewType.Steps);
        UpdateSteps(part);
    }

    private void ViewParts() { _part = null; _selected = null; View(ViewType.Parts); }

    private void ViewPart(EntityUid part)
    {
        _part = part;
        _selected = null;
        _procedures.Clear();
        Surgeries.RemoveAllChildren();
        Steps.RemoveAllChildren();
        UpdateProcedures(part);
        View(ViewType.Surgeries);
    }

    private void Update() { UpdateParts(); UpdateDisabledPanel();
        if (_part is not { } p) return;
        UpdateProcedures(p); UpdateSteps(p);
    }

    private void UpdateDisabledPanel()
    {
        if (_player.LocalEntity is not { } player || Deleted(_owner))
        {
            DisabledPanel.Visible = false;
            DisabledPanel.MouseFilter = MouseFilterMode.Ignore;
            return;
        }

        var lying = _graph.IsLyingDown(_owner, player, false);
        DisabledPanel.Visible = !lying;
        DisabledPanel.MouseFilter = lying ? MouseFilterMode.Ignore : MouseFilterMode.Stop;

        if (lying || DisabledLabel.GetMessage() is not null)
            return;

        var msg = new FormattedMessage();
        msg.AddMarkupOrThrow($"[color=red][font size=16]{Loc.GetString("surgery-error-laying")}[/font][/color]");
        DisabledLabel.SetMessage(msg);
    }

    private void UpdateParts()
    {
        var changed = false;
        _parts.RemoveAll(p =>
        {
            if (!Deleted(p) && (!_isBody || _body.GetBody(p) == _owner)) return false;
            if (_part == p) ViewParts();
            changed = true;
            return true;
        });
        if (_isBody)
        {
            foreach (var p in _body.GetExternalOrgans(_owner))
            {
                if (_parts.Contains(p)) continue;
                _parts.Add(p); changed = true;
            }
        }
        else if (!_parts.Contains(_owner)) { _parts.Add(_owner); changed = true; }
        if (changed) PartsChanged();
    }

    private void PartsChanged()
    {
        _parts.Sort((a, b) =>
        {
            int S(EntityUid u) => _partQuery.TryComp(u, out var p) ? p.PartType switch
            {
                BodyPartType.Head => 1,
                BodyPartType.Torso or BodyPartType.Arm => 2,
                BodyPartType.Hand => 3,
                BodyPartType.Leg => 4,
                BodyPartType.Foot => 5,
                BodyPartType.Tail => 6,
                BodyPartType.Wings => 7,
                _ => 9
            } : 9;
            return S(a) - S(b);
        });
        Parts.RemoveAllChildren();
        foreach (var p in _parts)
        {
            var btn = new ChoiceControl();
            var icon = _ent.GetComponentOrNull<SpriteComponent>(p)?.Icon?.Default;
            btn.Set(PartName(p), icon);
            btn.Button.OnPressed += _ => ViewPart(p);
            Parts.AddChild(btn);
        }
    }

    private void UpdateProcedures(EntityUid part)
    {
        var valid = _graph.GetAvailableProcedures(part);
        var changed = false;
        var deselected = false;
        _procedures.RemoveAll(e =>
        {
            if (valid.Contains(e)) return false;
            if (_selected == e) { _selected = null; deselected = true; }
            changed = true; return true;
        });
        foreach (var e in valid)
        {
            if (_procedures.Contains(e)) continue;
            _procedures.Add(e); changed = true;
        }
        if (changed) ProceduresChanged(part);

        if (!deselected)
            return;

        Steps.RemoveAllChildren();
        View(ViewType.Surgeries);
    }

    private void ProceduresChanged(EntityUid part)
    {
        _procedures.Sort((a, b) =>
        {
            var p = _proto.Index(a.Procedure).Priority.CompareTo(_proto.Index(b.Procedure).Priority);
            return p != 0 ? p : string.Compare(ProcedureName(a), ProcedureName(b), StringComparison.CurrentCulture);
        });
        Surgeries.RemoveAllChildren();
        foreach (var inst in _procedures)
        {
            var btn = new ChoiceControl();
            btn.Set(ProcedureName(inst), null);
            btn.Button.OnPressed += _ => ViewProcedure(part, inst);
            Surgeries.AddChild(btn);
        }
    }

    private void UpdateSteps(EntityUid part)
    {
        if (_selected is not { } inst || !_proto.TryIndex(inst.Procedure, out var proc) ||
            _player.LocalEntity is not { } player) return;

        var operated = _ent.GetComponentOrNull<OperatedComponent>(part);
        var completed = operated?.ActiveProcedure == inst.Procedure && operated.ActiveOrgan == inst.Organ
            ? operated.CompletedSteps : 0;
        var i = 0;
        foreach (var child in Steps.Children)
        {
            if (child is not ChoiceControl btn) continue;
            if (i < completed) { btn.Button.Disabled = true; btn.Button.Modulate = Color.Green; }
            else if (i == completed)
            {
                btn.Button.Disabled = false; btn.Button.Modulate = Color.White; btn.Button.ToolTip = null;
                if (!_graph.CanPerformStep(part, player, inst, i, out var popup))
                { btn.Button.Modulate = Color.Red; btn.Button.ToolTip = popup; }
            }
            else { btn.Button.Disabled = true; btn.Button.Modulate = Color.White; }
            i++;
        }
    }

    private void View(ViewType type)
    {
        Parts.Visible = type == ViewType.Parts; PartsButton.Disabled = type == ViewType.Parts;
        Surgeries.Visible = type == ViewType.Surgeries; SurgeriesButton.Disabled = type != ViewType.Steps;
        Steps.Visible = type == ViewType.Steps; StepsButton.Disabled = type != ViewType.Steps;
        if (_part is { } p && _ent.TryGetComponent(p, out MetaDataComponent? pm))
        {
            Title = _selected is { } inst
                ? Loc.GetString("trauma-surgery-title-procedure", ("part", pm.EntityName), ("surgery", ProcedureName(inst)))
                : Loc.GetString("trauma-surgery-title-part", ("part", pm.EntityName));
        }
        else Title = Loc.GetString("surgery-ui-window-title");
    }

    private enum ViewType : byte { Parts, Surgeries, Steps }
}
