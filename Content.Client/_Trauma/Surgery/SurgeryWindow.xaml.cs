using System.Numerics;
using Content.Client._Trauma.Choice.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Trauma.Body;
using Content.Shared._Trauma.Common.Body;
using Content.Shared._Trauma.Surgery.Graph;
using Content.Shared.Body;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Trauma.Surgery;

[GenerateTypedNameReferences]
public sealed partial class SurgeryWindow : FancyWindow
{
    private const float UpdateInterval = 0.2f;
    private static readonly Vector2 StripIconSize = new(24, 24);
    private static readonly Color PendingColor = Color.White.WithAlpha(0.45f);

    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    private BodySystem _body;
    private SurgeryGraphSystem _graph;
    private SpriteSystem _sprite;
    private EntityQuery<BodyPartComponent> _partQuery;

    public event Action<NetEntity, ProtoId<SurgeryProcedurePrototype>, int, ProtoId<OrganCategoryPrototype>?>? OnPerformStep;

    private readonly List<EntityUid> _parts = [];
    private readonly List<SurgeryProcedureInstance> _procedures = [];
    private EntityUid _owner;
    private bool _isBody;
    private EntityUid? _part;
    private SurgeryProcedureInstance? _selected;
    private float _updateTimer;

    public SurgeryWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _body = _ent.System<BodySystem>();
        _graph = _ent.System<SurgeryGraphSystem>();
        _sprite = _ent.System<SpriteSystem>();
        _partQuery = _ent.GetEntityQuery<BodyPartComponent>();

        PartsButton.OnPressed += _ => ViewParts();
        SurgeriesButton.OnPressed += _ => ViewPart();

        View(ViewType.Parts);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _updateTimer += args.DeltaSeconds;
        if (_updateTimer < UpdateInterval)
            return;

        _updateTimer = 0f;
        Update();
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
        _isBody = _ent.HasComponent<BodyComponent>(owner);
        Update();
    }

    private string PartName(EntityUid uid)
    {
        return _ent.GetComponent<MetaDataComponent>(uid).EntityName;
    }

    private string ProcedureName(SurgeryProcedureInstance instance)
    {
        var name = Loc.GetString(_proto.Index(instance.Procedure).Name);
        if (instance.Organ is not { } category || !_proto.TryIndex(category, out var categoryProto))
            return name;

        return Loc.GetString("surgery-procedure-organ", ("procedure", name), ("organ", categoryProto.Name));
    }

    private bool Deleted(EntityUid uid)
    {
        return !_ent.TryGetComponent(uid, out MetaDataComponent? meta) || meta.EntityDeleted;
    }

    private void ViewProcedure(EntityUid part, SurgeryProcedureInstance instance)
    {
        if (!_proto.TryIndex(instance.Procedure, out var procedure))
            return;

        _part = part;
        _selected = instance;
        Steps.RemoveAllChildren();
        StepStrip.RemoveAllChildren();

        var netPart = _ent.GetNetEntity(part);
        for (var i = 0; i < procedure.Steps.Count; i++)
        {
            var step = procedure.Steps[i];
            var index = i;

            var icon = step.Icon;
            if (icon == null && step.Quality is { } quality && _proto.TryIndex(quality, out var qualityProto))
                icon = qualityProto.Icon;

            var message = new FormattedMessage();
            message.AddText(Loc.GetString(step.Name));

            var texture = icon == null ? null : _sprite.Frame0(icon);
            var button = new ChoiceControl();
            button.Set(message, texture);
            button.Button.OnPressed += _ => OnPerformStep?.Invoke(netPart, instance.Procedure, index, instance.Organ);
            Steps.AddChild(button);

            StepStrip.AddChild(new TextureRect
            {
                Texture = texture,
                MinSize = StripIconSize,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                ToolTip = Loc.GetString(step.Name),
                Modulate = PendingColor
            });
        }

        View(ViewType.Steps);
        UpdateSteps(part);
    }

    private void ViewParts()
    {
        _part = null;
        _selected = null;
        View(ViewType.Parts);
    }

    private void ViewPart()
    {
        if (_part is { } part)
            ViewPart(part);
    }

    private void ViewPart(EntityUid part)
    {
        _part = part;
        _selected = null;
        _procedures.Clear();
        Surgeries.RemoveAllChildren();
        Steps.RemoveAllChildren();
        UpdateProcedures(part);
        View(ViewType.Surgeries);
    }

    private void Update()
    {
        UpdateParts();
        UpdateDisabledPanel();

        if (_part is not { } part)
            return;

        UpdateProcedures(part);
        UpdateSteps(part);
    }

    private void UpdateDisabledPanel()
    {
        var enabled = _player.LocalEntity == null || Deleted(_owner) || _graph.IsLyingDown(_owner);
        DisabledPanel.Visible = !enabled;
        DisabledPanel.MouseFilter = enabled ? MouseFilterMode.Ignore : MouseFilterMode.Stop;

        if (enabled || DisabledLabel.GetMessage() != null)
            return;

        var message = new FormattedMessage();
        message.PushColor(Color.Red);
        message.AddText(Loc.GetString("surgery-error-laying"));
        message.Pop();
        DisabledLabel.SetMessage(message);
    }

    private void UpdateParts()
    {
        var changed = _parts.RemoveAll(part =>
        {
            if (!Deleted(part) && (!_isBody || _body.GetBody(part) == _owner))
                return false;

            if (_part == part)
                ViewParts();

            return true;
        }) > 0;

        if (_isBody)
        {
            foreach (var part in _body.GetExternalOrgans(_owner))
            {
                if (_parts.Contains(part))
                    continue;

                _parts.Add(part);
                changed = true;
            }
        }
        else if (!_parts.Contains(_owner))
        {
            _parts.Add(_owner);
            changed = true;
        }

        if (changed)
            PartsChanged();
    }

    private int PartOrder(EntityUid uid)
    {
        if (!_partQuery.TryComp(uid, out var part))
            return 9;

        return part.PartType switch
        {
            BodyPartType.Head => 1,
            BodyPartType.Torso or BodyPartType.Arm => 2,
            BodyPartType.Hand => 3,
            BodyPartType.Leg => 4,
            BodyPartType.Foot => 5,
            BodyPartType.Tail => 6,
            BodyPartType.Wings => 7,
            _ => 9
        };
    }

    private void PartsChanged()
    {
        _parts.Sort((a, b) => PartOrder(a).CompareTo(PartOrder(b)));

        Parts.RemoveAllChildren();
        foreach (var part in _parts)
        {
            var button = new ChoiceControl();
            button.Set(PartName(part), _ent.GetComponentOrNull<SpriteComponent>(part)?.Icon?.Default);
            button.Button.OnPressed += _ => ViewPart(part);
            Parts.AddChild(button);
        }
    }

    private void UpdateProcedures(EntityUid part)
    {
        var valid = _graph.GetAvailableProcedures(part);
        var deselected = false;
        var changed = _procedures.RemoveAll(instance =>
        {
            if (valid.Contains(instance))
                return false;

            if (_selected != instance)
                return true;

            _selected = null;
            deselected = true;

            return true;
        }) > 0;

        foreach (var instance in valid)
        {
            if (_procedures.Contains(instance))
                continue;

            _procedures.Add(instance);
            changed = true;
        }

        if (changed)
            ProceduresChanged(part);

        if (!deselected)
            return;

        Steps.RemoveAllChildren();
        View(ViewType.Surgeries);
    }

    private void ProceduresChanged(EntityUid part)
    {
        _procedures.Sort((a, b) =>
        {
            var priority = _proto.Index(a.Procedure).Priority.CompareTo(_proto.Index(b.Procedure).Priority);
            return priority != 0
                ? priority
                : string.Compare(ProcedureName(a), ProcedureName(b), StringComparison.CurrentCulture);
        });

        Surgeries.RemoveAllChildren();
        foreach (var instance in _procedures)
        {
            var button = new ChoiceControl();
            button.Set(ProcedureName(instance), null);
            button.Button.OnPressed += _ => ViewProcedure(part, instance);
            Surgeries.AddChild(button);
        }
    }

    private void UpdateSteps(EntityUid part)
    {
        if (_selected is not { } instance || _player.LocalEntity is not { } player)
            return;

        var operated = _ent.GetComponentOrNull<OperatedComponent>(part);
        var completed = operated?.ActiveProcedure == instance.Procedure && operated.ActiveOrgan == instance.Organ
            ? operated.CompletedSteps
            : 0;

        for (var i = 0; i < StepStrip.ChildCount; i++)
        {
            StepStrip.GetChild(i).Modulate = i < completed ? Color.Green : i == completed ? Color.White : PendingColor;
        }

        var index = 0;
        foreach (var child in Steps.Children)
        {
            if (child is not ChoiceControl step)
                continue;

            step.Button.Disabled = index != completed;
            step.Button.ToolTip = null;
            step.Button.Modulate = index < completed ? Color.Green : Color.White;

            if (index == completed && !_graph.CanPerformStep(part, player, instance, index, out var popup))
            {
                step.Button.Modulate = Color.Red;
                step.Button.ToolTip = popup;
            }

            index++;
        }
    }

    private void View(ViewType type)
    {
        Parts.Visible = type == ViewType.Parts;
        PartsButton.Disabled = type == ViewType.Parts;

        Surgeries.Visible = type == ViewType.Surgeries;
        SurgeriesButton.Disabled = type != ViewType.Steps;

        Steps.Visible = type == ViewType.Steps;
        StepStrip.Visible = type == ViewType.Steps;
        if (type != ViewType.Steps)
            StepStrip.RemoveAllChildren();

        if (_part is not { } part || !_ent.TryGetComponent(part, out MetaDataComponent? meta))
        {
            Title = Loc.GetString("surgery-ui-window-title");
            return;
        }

        Title = _selected is { } instance
            ? Loc.GetString("trauma-surgery-title-procedure", ("part", meta.EntityName), ("surgery", ProcedureName(instance)))
            : Loc.GetString("trauma-surgery-title-part", ("part", meta.EntityName));
    }

    private enum ViewType : byte
    {
        Parts,
        Surgeries,
        Steps
    }
}
