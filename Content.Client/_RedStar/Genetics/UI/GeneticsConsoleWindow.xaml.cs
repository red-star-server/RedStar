using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Genetics.Data;
using Content.Shared._RedStar.Genetics.Prototypes;
using Content.Shared._RedStar.Genetics.UI;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._RedStar.Genetics.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticsConsoleWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly Dictionary<GeneticProcedure, Button> _procedures = new();
    private GeneticsConsoleUiState? _state;
    private ProtoId<GenePrototype>? _selected;
    public event Action<NetEntity, ProtoId<GenePrototype>, GeneticProcedure>? ProcedureRequested;
    public event Action? CancelRequested;

    public GeneticsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        GenePanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#252B35"),
            BorderColor = Color.FromHex("#6A9BA6"),
            BorderThickness = new Thickness(2, 0, 0, 0)
        };
        ProcedurePanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#252B35"),
            BorderColor = Color.FromHex("#6A9BA6"),
            BorderThickness = new Thickness(2, 0, 0, 0)
        };
        Progress.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#171C24") };
        Progress.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#85D5CA") };
        BeakerPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#202832"),
            BorderColor = Color.FromHex("#6A9BA6"),
            BorderThickness = new Thickness(0, 1, 0, 0)
        };
        Profile.Selectable = true;
        Profile.ShowConnection = false;
        Profile.GeneSelected += gene => { _selected = gene; RefreshSelection(); };
        Cancel.OnPressed += _ => CancelRequested?.Invoke();
    }

    /// <summary>
    /// Updates chamber availability and progress without changing the operator's gene selection.
    /// </summary>
    public void UpdateState(GeneticsConsoleUiState state)
    {
        if (_state?.Profile?.Target != state.Profile?.Target)
            _selected = null;
        _state = state;
        if (state.Profile is { } profile)
            Profile.UpdateState(profile);
        else
            Profile.Clear();
        Status.Text = state.Status switch
        {
            GeneticsConsoleStatus.NoChamber => Loc.GetString("genetics-console-no-chamber"),
            GeneticsConsoleStatus.NoPatient => Loc.GetString("genetics-console-no-patient"),
            _ => string.Empty
        };
        Status.Visible = state.Status is GeneticsConsoleStatus.NoChamber or GeneticsConsoleStatus.NoPatient;
        var beaker = state.Beaker is null
            ? Loc.GetString("genetics-console-no-beaker")
            : state.Beaker.Count == 0
                ? Loc.GetString("genetics-console-empty-beaker")
                : string.Join("\n", state.Beaker.Select(reagent =>
                    Loc.GetString("genetics-console-beaker-reagent",
                        ("reagent", _prototypes.Index<ReagentPrototype>(reagent.Reagent.Prototype).LocalizedName),
                        ("amount", reagent.Quantity))));
        Beaker.SetMessage(FormattedMessage.EscapeText(beaker));
        ProcedurePanel.Visible = state.Busy;
        Progress.Value = state.Progress;
        if (state.Busy && state.Operation is { } operation)
            Working.Text = Loc.GetString($"genetics-console-progress-{operation.ToString().ToLowerInvariant()}");

        RefreshSelection();
    }

    private void RefreshSelection()
    {
        foreach (var button in _procedures.Values)
        {
            button.Visible = false;
        }

        Description.Visible = GeneState.Visible = false;
        Procedures.Visible = false;
        Description.SetMessage(string.Empty);
        GeneState.Text = string.Empty;
        SelectedName.Text = Loc.GetString("genetics-console-select-gene");
        SelectedName.ToolTip = null;
        if (_state?.Profile is not { } profile || _selected is not { } gene || !profile.Genes.Any(entry => entry.Id == gene))
            return;
        var entry = profile.Genes.First(entry => entry.Id == gene);
        SelectedName.Text = Loc.GetString($"gene-{gene}-name");
        SelectedName.ToolTip = SelectedName.Text;
        Description.Visible = GeneState.Visible = true;
        Description.SetMessage(Loc.GetString($"gene-{gene}-desc"));
        GeneState.Text = Loc.GetString(entry.Status switch
        {
            GeneStatus.Raw => "genetic-analyzer-dormant",
            GeneStatus.Suppressed => "genetic-analyzer-suppressed",
            GeneStatus.Active => "genetic-analyzer-connected",
            _ => "genetics-console-natural"
        });
        GeneState.ToolTip = GeneState.Text;
        if (entry.Status is null)
            return;
        Procedures.Visible = true;
        foreach (var procedure in _state.Procedures)
        {
            if (!procedure.Procedure.CanProcess(entry.Status))
                continue;
            if (!_procedures.TryGetValue(procedure.Procedure, out var button))
            {
                var kind = procedure.Procedure;
                button = new Button { MinHeight = 32, Text = Loc.GetString($"genetics-console-{kind.ToString().ToLowerInvariant()}") };
                button.OnPressed += _ =>
                {
                    if (_state?.Profile?.Target is { } patient && _selected is { } selected)
                        ProcedureRequested?.Invoke(patient, selected, kind);
                };
                Procedures.AddChild(button);
                _procedures.Add(kind, button);
            }
            button.Visible = true;
            button.Disabled = _state.Busy || !procedure.CanStart;
        }
    }
}
