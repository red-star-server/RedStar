using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Genetics.Data;
using Content.Shared._RedStar.Genetics.Prototypes;
using Content.Shared._RedStar.Genetics.UI;
using Content.Shared.Humanoid;
using Content.Shared.IdentityManagement;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._RedStar.Genetics.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticAnalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly Dictionary<ProtoId<GenePrototype>, GeneRow> _rows = new();
    private GeneticAnalyzerUiState? _state;

    public GeneticAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        PatientPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#202832"),
            BorderColor = Color.FromHex("#6A9BA6"),
            BorderThickness = new Thickness(0, 0, 0, 2)
        };
        LoadBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#171C24") };
        Search.OnTextChanged += _ => FilterGenes();
        PatientName.Text = Loc.GetString("genetic-analyzer-no-data");
    }

    /// <summary>
    /// Refreshes the report without closing gene details or losing the current search and scroll position.
    /// </summary>
    public void UpdateState(GeneticAnalyzerUiState state)
    {
        var changedPatient = _state?.Target != state.Target;
        var changedGenes = _state is null || !_state.Genes.SequenceEqual(state.Genes);
        _state = state;

        var target = _entities.GetEntity(state.Target);
        var available = target is { } uid && !_entities.Deleted(uid);
        PatientSprite.Visible = available && state.InRange;
        NoPatient.Visible = !PatientSprite.Visible;
        if (available)
        {
            PatientSprite.SetEntity(target!.Value);
            PatientName.Text = Identity.Name(target.Value, _entities);
            Species.Text = _entities.TryGetComponent<HumanoidProfileComponent>(target, out var humanoid)
                ? Loc.GetString(_prototypes.Index(humanoid.Species).Name)
                : Loc.GetString("genetic-analyzer-organism");
        }
        Connection.Text = Loc.GetString(state.InRange ? "genetic-analyzer-connected" : "genetic-analyzer-disconnected");
        Connection.FontColorOverride = state.InRange ? Color.Green : Color.Red;

        var overloaded = state.Load > state.MaximumLoad;
        var full = state.Load >= state.MaximumLoad && state.Load > 0;
        var loadColor = Color.FromHex(overloaded ? "#E08086" : full ? "#E0B773" : "#85D5CA");
        LoadValue.Text = Loc.GetString("genetic-analyzer-load-value", ("load", state.Load), ("maximum", state.MaximumLoad));
        LoadValue.FontColorOverride = loadColor;
        LoadBar.Value = state.MaximumLoad > 0 ? Math.Clamp((float) state.Load / state.MaximumLoad, 0, 1) : state.Load > 0 ? 1 : 0;
        LoadBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = loadColor };
        LoadStatus.Text = Loc.GetString(overloaded ? "genetic-analyzer-overloaded" : full ? "genetic-analyzer-full" : "genetic-analyzer-normal");
        GeneCount.Text = Loc.GetString("genetic-analyzer-count", ("count", state.Genes.Count));

        if (!changedPatient && !changedGenes)
            return;

        var expanded = changedPatient ? new HashSet<ProtoId<GenePrototype>>() : _rows.Where(row => row.Value.Expanded).Select(row => row.Key).ToHashSet();
        GeneList.RemoveAllChildren();
        _rows.Clear();
        foreach (var entry in state.Genes.OrderBy(gene => Loc.GetString($"gene-{gene.Id}-name")))
        {
            var row = new GeneRow(_prototypes.Index(entry.Id), entry.Status, expanded.Contains(entry.Id));
            _rows.Add(entry.Id, row);
            GeneList.AddChild(row);
        }
        if (changedPatient)
            Search.Text = string.Empty;
        FilterGenes();
    }

    private void FilterGenes()
    {
        var query = Search.Text.Trim();
        foreach (var row in _rows.Values)
        {
            row.Visible = row.GeneName.Contains(query, StringComparison.CurrentCultureIgnoreCase);
        }

        Empty.Visible = _state is not null && !_rows.Values.Any(row => row.Visible);
    }

    private sealed class GeneRow : PanelContainer
    {
        public string GeneName { get; }
        public bool Expanded => _details.Visible;
        private readonly BoxContainer _details;

        public GeneRow(GenePrototype gene, GeneStatus? status, bool expanded)
        {
            GeneName = Loc.GetString($"gene-{gene.ID}-name");
            var color = CategoryColor(gene.Category);
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#252B35"),
                BorderColor = color,
                BorderThickness = new Thickness(3, 0, 0, 0)
            };
            var body = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 6,
                Margin = new Thickness(9, 7),
                HorizontalExpand = true
            };
            AddChild(body);
            var header = new BoxContainer { SeparationOverride = 8 };
            body.AddChild(header);
            header.AddChild(new Label { Text = GeneName, HorizontalExpand = true, ClipText = true, ToolTip = GeneName });
            header.AddChild(new Label
            {
                Text = Loc.GetString($"genetic-analyzer-category-{gene.Category.ToString().ToLowerInvariant()}"),
                FontColorOverride = color
            });
            var toggle = new Button { Text = expanded ? "−" : "+", MinWidth = 28, ToggleMode = true, Pressed = expanded };
            toggle.ToolTip = Loc.GetString("genetic-analyzer-details");
            header.AddChild(toggle);
            if (status is GeneStatus.Raw or GeneStatus.Suppressed)
            {
                body.AddChild(new Label
                {
                    Text = Loc.GetString(status == GeneStatus.Raw ? "genetic-analyzer-dormant" : "genetic-analyzer-suppressed"),
                    FontColorOverride = Color.FromHex("#E0B773")
                });
            }
            _details = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 6,
                Visible = expanded
            };
            var description = new RichTextLabel { HorizontalExpand = true };
            description.SetMessage(Loc.GetString($"gene-{gene.ID}-desc"));
            _details.AddChild(description);
            _details.AddChild(new Label
            {
                Text = Loc.GetString("genetic-analyzer-gene-load", ("load", gene.LoadCost)),
                StyleClasses = { "LabelSubText" }
            });
            body.AddChild(_details);
            toggle.OnToggled += args =>
            {
                _details.Visible = args.Pressed;
                toggle.Text = args.Pressed ? "−" : "+";
            };
        }

        private static Color CategoryColor(GeneCategory category) => Color.FromHex(category switch
        {
            GeneCategory.Beneficial => "#85D5AD",
            GeneCategory.Pathological => "#E58D98",
            GeneCategory.Mixed => "#E0BE7D",
            GeneCategory.Cosmetic => "#C0A5E0",
            _ => "#9ABBD1"
        });
    }
}
