using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Xenobiology.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._RedStar.Xenobiology.UI;

[GenerateTypedNameReferences]
public sealed partial class CellularFusionWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    public event Action<int, int>? OnSplice;

    private readonly List<CellEntryControl> _selected = [];
    private IReadOnlyList<SampleView> _samples = [];
    private NetEntity? _dish;
    private bool _spliceInProgress;
    private TimeSpan _spliceStartTime;
    private double _spliceDuration;

    public CellularFusionWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        CellInfoA.SetLabelPrefix("cellular-fusion-menu");
        CellInfoB.SetLabelPrefix("cellular-fusion-menu");
        SpliceButton.OnPressed += _ =>
        {
            if (_selected.Count == 2 && !_spliceInProgress)
                OnSplice?.Invoke(_selected[0].Id, _selected[1].Id);
        };
    }

    public void UpdateState(CellularFusionUiState state)
    {
        var contentsChanged = _dish != state.Dish ||
            !SameSamples(_samples, state.Samples);
        _dish = state.Dish;

        if (contentsChanged)
            RebuildEntries(state.Samples);

        _spliceInProgress = state.SpliceInProgress;

        if (_spliceInProgress)
        {
            _spliceDuration = state.SpliceDuration;
            _spliceStartTime = _timing.RealTime - TimeSpan.FromSeconds(
                Math.Max(0, state.SpliceDuration - state.SpliceRemaining));
        }

        foreach (var entry in CellContainer.Children.OfType<CellEntryControl>())
        {
            entry.SetEnabled(!_spliceInProgress);
        }

        NoDishLabel.Visible = state.Dish is null;
        EmptyDishLabel.Visible = state.Dish is not null && state.Samples.Length == 0;
        SpliceProgressBar.Visible = _spliceInProgress;
        UpdateDetails();
    }

    private void RebuildEntries(IReadOnlyList<SampleView> cells)
    {
        _selected.Clear();
        _samples = cells.ToArray();
        CellContainer.RemoveAllChildren();
        foreach (var t in cells)
        {
            var entry = new CellEntryControl(t, t.Id);
            entry.OnSelect += SelectEntry;
            CellContainer.AddChild(entry);
        }
    }

    private static bool SameSamples(IReadOnlyList<SampleView> left, IReadOnlyList<SampleView> right)
    {
        if (left.Count != right.Count)
            return false;
        for (var i = 0; i < left.Count; i++)
        {
            if (!left[i].SameDisplay(right[i]))
                return false;
        }
        return true;
    }

    private void SelectEntry(CellEntryControl entry)
    {
        if (_spliceInProgress)
            return;

        if (_selected.Remove(entry))
            entry.SetSelected(false);
        else
        {
            if (_selected.Count == 2)
            {
                _selected[0].SetSelected(false);
                _selected.RemoveAt(0);
            }
            _selected.Add(entry);
            entry.SetSelected(true);
        }

        UpdateDetails();
    }

    private void UpdateDetails()
    {
        var count = _selected.Count;
        NoSelectionLabel.Visible = count == 0;
        CellInfoA.Visible = count > 0;
        CellInfoB.Visible = count == 2;
        InfoDivider.Visible = count == 2;

        if (count > 0)
            CellInfoA.SetSample(_selected[0].Sample);
        if (count == 2)
            CellInfoB.SetSample(_selected[1].Sample);

        SpliceButton.Disabled = _spliceInProgress || count != 2 ||
            !_selected[0].Sample.HasGenome || !_selected[1].Sample.HasGenome ||
            Math.Max(_selected[0].Sample.Stability, _selected[1].Sample.Stability) >= 1f;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_spliceInProgress)
            return;

        var elapsed = (_timing.RealTime - _spliceStartTime).TotalSeconds;
        SpliceProgressBar.Value = _spliceDuration > 0
            ? (float) Math.Clamp(elapsed / _spliceDuration * 100.0, 0.0, 100.0)
            : 0;
    }
}
