using Content.Shared._RedStar.Xenobiology.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RedStar.Xenobiology.UI;

[GenerateTypedNameReferences]
public sealed partial class SampleEntryControl : Control
{
    public readonly SampleView Sample;
    public event Action<SampleEntryControl>? OnSelect;

    public SampleEntryControl(SampleView sample)
    {
        RobustXamlLoader.Load(this);
        Sample = sample;

        SampleNameLabel.Text = sample.Name;
        Color.ModulateSelfOverride = sample.Color;

        Button.OnPressed += _ => OnSelect?.Invoke(this);
    }

    public void SetSelected(bool selected)
    {
        Button.ToggleMode = true;
        Button.Pressed = selected;
    }

    public void SetEnabled(bool enabled)
    {
        Button.Disabled = !enabled;
    }
}
