using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Xenobiology.UI;
using Content.Shared._RedStar.Xenobiology.Components.Machines;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._RedStar.Xenobiology.UI;

[GenerateTypedNameReferences]
public sealed partial class SampleStabilizerWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<NetEntity, int>? OnStabilization;

    private SampleEntryControl? _selected;
    private IReadOnlyList<SampleView> _samples = [];
    private SampleStabilizerUiState? _state;
    private NetEntity? _dish;
    private bool _stabilizationInProgress;

    /// <summary>
    /// Machine whose replicated completion time and pause state drive the progress bar.
    /// </summary>
    public EntityUid Owner;
    private double _stabilizationDuration;

    public SampleStabilizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        StabilizationButton.OnPressed += _ =>
        {
            if (_selected is { } selected && _dish is { } dish && !_stabilizationInProgress)
                OnStabilization?.Invoke(dish, selected.Sample.Id);
        };
    }

    /// <summary>
    /// Refreshes sample selection and stabilization controls. A changed dish or sample list clears the selection.
    /// </summary>
    public void UpdateState(SampleStabilizerUiState state)
    {
        var contentsChanged = _dish != state.Dish ||
            !_samples.SequenceEqual(state.Samples);
        _state = state;
        _dish = state.Dish;

        if (contentsChanged)
            RebuildEntries(state.Samples);

        _stabilizationInProgress = state.StabilizationInProgress;

        if (_stabilizationInProgress)
            _stabilizationDuration = state.StabilizationDuration;

        foreach (var entry in SampleContainer.Children.OfType<SampleEntryControl>())
        {
            entry.SetEnabled(!_stabilizationInProgress);
        }

        NoDishLabel.Visible = state.Dish is null;
        EmptyDishLabel.Visible = state.Dish is not null && state.Samples.Length == 0;
        StabilizationProgressBar.Visible = _stabilizationInProgress;
        UpdateDetails();
    }

    private void RebuildEntries(IReadOnlyList<SampleView> samples)
    {
        _selected = null;
        _samples = samples.ToArray();
        SampleContainer.RemoveAllChildren();
        foreach (var sample in samples)
        {
            var entry = new SampleEntryControl(sample);
            entry.OnSelect += SelectEntry;
            SampleContainer.AddChild(entry);
        }
    }

    private void SelectEntry(SampleEntryControl entry)
    {
        if (_stabilizationInProgress)
            return;

        foreach (var other in SampleContainer.Children.OfType<SampleEntryControl>())
        {
            other.SetSelected(other == entry);
        }

        _selected = entry;
        UpdateDetails();
    }

    private void UpdateDetails()
    {
        NoSelectionLabel.Visible = _selected is null;
        SampleInfo.Visible = _selected is not null;
        if (_selected is { } selected)
            SampleInfo.SetSample(selected.Sample);

        StabilizationButton.Disabled = true;
        if (_state is not { } state)
            return;

        var reagent = _prototypes.Index(state.Reagent).LocalizedName;
        if (!state.BeakerInserted)
        {
            ReagentLabel.SetMessage(Loc.GetString("sample-stabilizer-menu-no-beaker-label", ("reagent", reagent)));
            return;
        }

        if (_selected is not { } sample)
        {
            ReagentLabel.SetMessage(Loc.GetString("sample-stabilizer-menu-reagent-label",
                ("reagent", reagent), ("amount", state.ReagentAmount)));
            return;
        }

        var gain = MathF.Min(state.MaximumGain, 1f - sample.Sample.Stability);
        var cost = FixedPoint2.New(gain / state.StabilityPerUnit);
        if (!sample.Sample.HasGenome || gain <= 0f || cost <= FixedPoint2.Zero)
        {
            ReagentLabel.SetMessage(Loc.GetString("sample-stabilizer-menu-nothing-label"));
            return;
        }

        ReagentLabel.SetMessage(Loc.GetString("sample-stabilizer-menu-cost-label",
            ("reagent", reagent), ("amount", state.ReagentAmount), ("cost", cost), ("gain", Math.Round(gain * 100f, 1))));
        StabilizationButton.Disabled = _stabilizationInProgress || state.ReagentAmount < cost;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_stabilizationInProgress)
            return;

        if (!_entities.TryGetComponent<SampleStabilizerComponent>(Owner, out var stabilizer) ||
            stabilizer.StabilizationEndTime is not { } endTime)
            return;

        var time = _timing.CurTime - _entities.System<MetaDataSystem>().GetPauseTime(Owner);
        var elapsed = _stabilizationDuration - (endTime - time).TotalSeconds;
        StabilizationProgressBar.Value = _stabilizationDuration > 0
            ? (float) Math.Clamp(elapsed / _stabilizationDuration * 100.0, 0.0, 100.0)
            : 0;
    }
}
