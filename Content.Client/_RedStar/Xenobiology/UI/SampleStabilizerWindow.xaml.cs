using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Xenobiology.UI;
using Content.Shared._RedStar.Xenobiology.Components.Machines;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._RedStar.Xenobiology.UI;

[GenerateTypedNameReferences]
public sealed partial class SampleStabilizerWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEntityManager _entities = default!;

    public event Action<int, int>? OnStabilization;

    private readonly List<SampleEntryControl> _selected = [];
    private IReadOnlyList<SampleView> _samples = [];
    private NetEntity? _dish;
    private bool _stabilizationInProgress;

    /// <summary>
    /// Machine whose replicated completion time and pause state drive the progress bar.
    /// </summary>
    public EntityUid Owner;
    private double _stabilizationDuration;

    public SampleStabilizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SampleInfoA.SetLabelPrefix("sample-stabilizer-menu");
        SampleInfoB.SetLabelPrefix("sample-stabilizer-menu");
        StabilizationButton.OnPressed += _ =>
        {
            if (_selected.Count == 2 && !_stabilizationInProgress)
                OnStabilization?.Invoke(_selected[0].Sample.Id, _selected[1].Sample.Id);
        };
    }

    /// <summary>
    /// Refreshes sample selection and stabilization controls. A changed dish or sample list clears the selection.
    /// </summary>
    public void UpdateState(SampleStabilizerUiState state)
    {
        var contentsChanged = _dish != state.Dish ||
            !_samples.SequenceEqual(state.Samples);
        _dish = state.Dish;

        if (contentsChanged)
            RebuildEntries(state.Samples);

        _stabilizationInProgress = state.StabilizationInProgress;

        if (_stabilizationInProgress)
        {
            _stabilizationDuration = state.StabilizationDuration;
        }

        foreach (var entry in SampleContainer.Children.OfType<SampleEntryControl>())
        {
            entry.SetEnabled(!_stabilizationInProgress);
        }

        NoDishLabel.Visible = state.Dish is null;
        EmptyDishLabel.Visible = state.Dish is not null && state.Samples.Length == 0;
        StabilizationProgressBar.Visible = _stabilizationInProgress;
        UpdateDetails();
    }

    private void RebuildEntries(IReadOnlyList<SampleView> samples)
    {
        _selected.Clear();
        _samples = samples.ToArray();
        SampleContainer.RemoveAllChildren();
        foreach (var t in samples)
        {
            var entry = new SampleEntryControl(t);
            entry.OnSelect += SelectEntry;
            SampleContainer.AddChild(entry);
        }
    }

    private void SelectEntry(SampleEntryControl entry)
    {
        if (_stabilizationInProgress)
            return;

        if (_selected.Remove(entry))
            entry.SetSelected(false);
        else
        {
            if (_selected.Count == 2)
            {
                _selected[0].SetSelected(false);
                _selected.RemoveAt(0);
            }
            _selected.Add(entry);
            entry.SetSelected(true);
        }

        UpdateDetails();
    }

    private void UpdateDetails()
    {
        var count = _selected.Count;
        NoSelectionLabel.Visible = count == 0;
        SampleInfoA.Visible = count > 0;
        SampleInfoB.Visible = count == 2;
        InfoDivider.Visible = count == 2;

        if (count > 0)
            SampleInfoA.SetSample(_selected[0].Sample);
        if (count == 2)
            SampleInfoB.SetSample(_selected[1].Sample);

        var incompatible = count == 2 &&
            _selected[0].Sample.CompatibilityGroup != _selected[1].Sample.CompatibilityGroup;
        IncompatibleLabel.Visible = incompatible;
        if (incompatible)
            IncompatibleLabel.SetMessage(Loc.GetString("sample-stabilizer-incompatible"));

        StabilizationButton.Disabled = _stabilizationInProgress || count != 2 || incompatible ||
            !_selected[0].Sample.HasGenome || !_selected[1].Sample.HasGenome ||
            Math.Max(_selected[0].Sample.Stability, _selected[1].Sample.Stability) >= 1f;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_stabilizationInProgress)
            return;

        if (!_entities.TryGetComponent<SampleStabilizerComponent>(Owner, out var stabilizer) ||
            stabilizer.StabilizationEndTime is not { } endTime)
            return;

        var time = _timing.CurTime - _entities.System<MetaDataSystem>().GetPauseTime(Owner);
        var elapsed = _stabilizationDuration - (endTime - time).TotalSeconds;
        StabilizationProgressBar.Value = _stabilizationDuration > 0
            ? (float) Math.Clamp(elapsed / _stabilizationDuration * 100.0, 0.0, 100.0)
            : 0;
    }
}
