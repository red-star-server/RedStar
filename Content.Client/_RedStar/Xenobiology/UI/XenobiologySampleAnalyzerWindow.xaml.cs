using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Xenobiology.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RedStar.Xenobiology.UI;

[GenerateTypedNameReferences]
public sealed partial class XenobiologySampleAnalyzerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;

    public event Action? AnalyzeRequested;

    public XenobiologySampleAnalyzerWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        AnalyzeButton.OnPressed += _ => AnalyzeRequested?.Invoke();
    }

    public void UpdateState(XenobiologySampleAnalyzerUiState state)
    {
        EntityUid? sample = null;
        if (state.Sample is { } net && _entities.TryGetEntity(net, out var uid) &&
            uid is { } local && !_entities.Deleted(local))
            sample = local;

        if (SampleView.Entity?.Owner != sample)
            SampleView.SetEntity(sample);

        AnalysisProgress.Value = state.Progress;
        AnalyzeButton.Disabled = state.Status != XenobiologySampleStatus.Ready;
        StatusLabel.Text = state.Status switch
        {
            XenobiologySampleStatus.Empty => Loc.GetString("xenobiology-analyzer-sample-empty"),
            XenobiologySampleStatus.NoServer => Loc.GetString("xenobiology-analyzer-no-server"),
            XenobiologySampleStatus.Unpowered => Loc.GetString("xenobiology-analyzer-unpowered"),
            XenobiologySampleStatus.Unmatched => Loc.GetString("xenobiology-analyzer-no-target"),
            XenobiologySampleStatus.Ready => Loc.GetString("xenobiology-analyzer-ready"),
            XenobiologySampleStatus.Processing => Loc.GetString("xenobiology-analyzer-processing"),
            XenobiologySampleStatus.Complete => Loc.GetString("xenobiology-analyzer-complete", ("points", state.Reward ?? 0)),
            _ => string.Empty
        };
    }
}
