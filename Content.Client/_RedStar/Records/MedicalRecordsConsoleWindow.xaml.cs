using Content.Client.StationRecords;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Records;
using Content.Shared.Access;
using Content.Shared.Access.Systems;
using Robust.Client.Player;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Robust.Shared.Prototypes;

namespace Content.Client._RedStar.Records;

[GenerateTypedNameReferences]
public sealed partial class MedicalRecordsConsoleWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    public event Action<uint?>? OnSelected;
    public event Action<MedicalTriagePriority>? OnPriorityChanged;
    private readonly IPlayerManager _players;
    private readonly AccessReaderSystem _access;
    private bool _updating;
    private MedicalRecordsConsoleState? _state;

    public MedicalRecordsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _players = IoCManager.Resolve<IPlayerManager>();
        _access = IoCManager.Resolve<IEntityManager>().System<AccessReaderSystem>();
        RecordListing.OnItemSelected += args =>
        {
            if (!_updating && RecordListing[args.ItemIndex].Metadata is uint key)
                OnSelected?.Invoke(key);
        };
        RecordListing.OnItemDeselected += _ =>
        {
            if (!_updating)
                OnSelected?.Invoke(null);
        };
        SearchEdit.OnTextChanged += _ => RebuildListing();

        foreach (var priority in Enum.GetValues<MedicalTriagePriority>())
            PriorityOptionButton.AddItem(Loc.GetString($"medical-triage-{priority.ToString().ToLowerInvariant()}"), (int) priority);
        PriorityOptionButton.OnItemSelected += args =>
        {
            if (!_updating)
                OnPriorityChanged?.Invoke((MedicalTriagePriority) args.Id);
        };
    }

    private void RebuildListing()
    {
        if (_state == null)
            return;

        _updating = true;
        RecordListing.Clear();
        var filter = SearchEdit.Text.Trim();
        foreach (var (key, name) in _state.Listing)
        {
            if (!string.IsNullOrEmpty(filter) &&
                !name.Contains(filter, StringComparison.OrdinalIgnoreCase))
                continue;

            var item = RecordListing.AddItem(name);
            item.Metadata = key;
            item.Selected = key == _state.SelectedKey;
        }
        RecordListing.SortItemsByText();
        _updating = false;
    }

    public void UpdateState(MedicalRecordsConsoleState state)
    {
        var previous = _state;
        var updateListing = previous == null || previous.SelectedKey != state.SelectedKey ||
                            previous.Listing.Count != state.Listing.Count;
        if (!updateListing && previous != null)
        {
            foreach (var (key, name) in state.Listing)
            {
                if (previous.Listing.TryGetValue(key, out var oldName) && oldName == name)
                    continue;

                updateListing = true;
                break;
            }
        }
        _state = state;
        if (updateListing)
            RebuildListing();

        RecordDetails.RemoveAllChildren();
        TriagePanel.Visible = state.GeneralRecord != null;
        if (state.GeneralRecord == null)
            return;

        RecordDetails.AddChild(new GeneralRecord(state.GeneralRecord, false, null, _prototypes));
        if (state.Dossier != null)
            RecordDetails.AddChild(new CharacterDossierView(state.Dossier, DossierSection.Medical));

        var priority = state.Triage ?? MedicalTriagePriority.None;
        _updating = true;
        PriorityOptionButton.SelectId((int) priority);
        _updating = false;
        var canEdit = _players.LocalEntity is { } actor &&
                      _access.FindAccessTags(actor).Contains(new ProtoId<AccessLevelPrototype>("Medical"));
        PriorityOptionButton.Disabled = !canEdit;
        PriorityIcon.Visible = priority != MedicalTriagePriority.None;
        if (priority != MedicalTriagePriority.None)
        {
            PriorityIcon.SetFromSpriteSpecifier(new SpriteSpecifier.Rsi(
                new ResPath("_RedStar/Interface/Misc/triage_icons.rsi"), priority.ToString().ToLowerInvariant()));
        }
    }
}
