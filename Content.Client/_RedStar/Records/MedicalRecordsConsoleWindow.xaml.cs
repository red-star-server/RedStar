using Content.Client.StationRecords;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Records;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._RedStar.Records;

[GenerateTypedNameReferences]
public sealed partial class MedicalRecordsConsoleWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    public event Action<uint?>? OnSelected;
    private bool _updating;

    public MedicalRecordsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RecordListing.OnItemSelected += args =>
        {
            if (!_updating && RecordListing[args.ItemIndex].Metadata is uint key)
                OnSelected?.Invoke(key);
        };
        RecordListing.OnItemDeselected += _ =>
        {
            if (!_updating)
                OnSelected?.Invoke(null);
        };
    }

    public void UpdateState(MedicalRecordsConsoleState state)
    {
        _updating = true;
        RecordListing.Clear();
        foreach (var (key, name) in state.Listing)
        {
            var item = RecordListing.AddItem(name);
            item.Metadata = key;
            item.Selected = key == state.SelectedKey;
        }
        RecordListing.SortItemsByText();
        _updating = false;

        RecordDetails.RemoveAllChildren();
        if (state.GeneralRecord != null)
            RecordDetails.AddChild(new GeneralRecord(state.GeneralRecord, false, null, _prototypes));
        if (state.Dossier != null)
            RecordDetails.AddChild(new CharacterDossierView(state.Dossier, DossierSection.Medical));
    }
}
