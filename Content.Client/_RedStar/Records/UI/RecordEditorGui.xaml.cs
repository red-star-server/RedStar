using Content.Shared.Preferences;
using Content.Shared._RedStar.Records;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface;

namespace Content.Client._RedStar.Records.UI;

/// <summary>
/// The record editor tab that gets "injected" into the character editor.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RecordEditorGui : Control
{
    /// <summary>
    /// Delegate that tells the editor to save records when the save button is pressed
    /// </summary>
    private readonly Action<CharacterDossier> _updateProfileRecords;
    private CharacterDossier _records = default!;
    private bool _updating;

    public RecordEditorGui(Action<CharacterDossier> updateProfileRecords)
    {
        RobustXamlLoader.Load(this);
        _updateProfileRecords = updateProfileRecords;

        #region General

        WeightEdit.OnTextChanged += args =>
        {
            if (!int.TryParse(args.Text, out var newWeight))
                return;
            UpdateRecords(_records.WithWeight(newWeight));
        };

        ContactNameEdit.OnTextChanged += args =>
        {
            UpdateRecords(_records.WithEmergencyContact(args.Text));
        };
        ResidenceEdit.OnTextChanged += args => UpdateRecords(_records.WithResidence(args.Text));
        GeneralNotesEdit.OnTextChanged += args => UpdateRecords(_records.WithGeneralNotes(args.Text));

        #endregion

        #region Employment

        EducationEdit.OnTextChanged += args => UpdateRecords(_records.WithEducation(args.Text));
        PreviousEmploymentEdit.OnTextChanged += args => UpdateRecords(_records.WithPreviousEmployment(args.Text));
        ProfessionalExperienceEdit.OnTextChanged += args => UpdateRecords(_records.WithProfessionalExperience(args.Text));
        EmploymentNotesEdit.OnTextChanged += args => UpdateRecords(_records.WithEmploymentNotes(args.Text));

        #endregion

        #region Security

        IdentifyingFeaturesEdit.OnTextChanged += args =>
        {
            UpdateRecords(_records.WithIdentifyingFeatures(args.Text));
        };
        SecurityBackgroundEdit.OnTextChanged += args => UpdateRecords(_records.WithSecurityBackground(args.Text));
        SecurityNotesEdit.OnTextChanged += args => UpdateRecords(_records.WithSecurityNotes(args.Text));

        #endregion

        #region Medical

        AllergiesEdit.OnTextChanged += args =>
        {
            UpdateRecords(_records.WithAllergies(args.Text));
        };

        DrugAllergiesEdit.OnTextChanged += args =>
        {
            UpdateRecords(_records.WithDrugAllergies(args.Text));
        };
        MedicalConditionsEdit.OnTextChanged += args => UpdateRecords(_records.WithMedicalConditions(args.Text));
        PrescriptionsEdit.OnTextChanged += args => UpdateRecords(_records.WithPrescriptions(args.Text));

        PostmortemEdit.OnTextChanged += args =>
        {
            UpdateRecords(_records.WithPostmortemInstructions(args.Text));
        };

        #endregion

        #region Entries

        EntryEditorTabs.SetTabTitle(0, Loc.GetString("humanoid-profile-editor-cd-records-employment"));
        EntryEditorTabs.SetTabTitle(1, Loc.GetString("department-Medical"));
        EntryEditorTabs.SetTabTitle(2, Loc.GetString("department-Security"));

        EmploymentEntrySelector.OnUpdateEntries += args =>
        {
            UpdateRecords(_records.WithEmploymentEntries(args.Entries));
        };

        MedicalEntrySelector.OnUpdateEntries += args =>
        {
            UpdateRecords(_records.WithMedicalEntries(args.Entries));
        };

        SecurityEntrySelector.OnUpdateEntries += args =>
        {
            UpdateRecords(_records.WithSecurityEntries(args.Entries));
        };

        #endregion
    }

    public void Update(HumanoidCharacterProfile? profile)
    {
        _records = profile?.Dossier is { } dossier ? dossier.DeepCopy() : new CharacterDossier();
        EmploymentEntrySelector.UpdateContents(_records.EmploymentEntries);
        MedicalEntrySelector.UpdateContents(_records.MedicalEntries);
        SecurityEntrySelector.UpdateContents(_records.SecurityEntries);
        UpdateWidgets();
    }

    private void UpdateRecords(CharacterDossier records)
    {
        if (_updating)
            return;

        records.EnsureValid();
        _records = records;
        _updateProfileRecords(_records);
        UpdateWidgets();
    }

    private void UpdateWidgets()
    {
        _updating = true;
        WeightEdit.SetText(_records.Weight.ToString());
        ContactNameEdit.SetText(_records.EmergencyContact);
        ResidenceEdit.SetText(_records.Residence);
        GeneralNotesEdit.SetText(_records.GeneralNotes);

        EducationEdit.SetText(_records.Education);
        PreviousEmploymentEdit.SetText(_records.PreviousEmployment);
        ProfessionalExperienceEdit.SetText(_records.ProfessionalExperience);
        EmploymentNotesEdit.SetText(_records.EmploymentNotes);

        IdentifyingFeaturesEdit.SetText(_records.IdentifyingFeatures);
        SecurityBackgroundEdit.SetText(_records.SecurityBackground);
        SecurityNotesEdit.SetText(_records.SecurityNotes);

        AllergiesEdit.SetText(_records.Allergies);
        DrugAllergiesEdit.SetText(_records.DrugAllergies);
        MedicalConditionsEdit.SetText(_records.MedicalConditions);
        PrescriptionsEdit.SetText(_records.Prescriptions);
        PostmortemEdit.SetText(_records.PostmortemInstructions);
        _updating = false;
    }

}
