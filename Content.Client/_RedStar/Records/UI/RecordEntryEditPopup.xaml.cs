using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Records;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RedStar.Records.UI;

[GenerateTypedNameReferences]
public sealed partial class RecordEntryEditPopup : FancyWindow
{
    private bool _isValid;

    public RecordEntryEditPopup()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ValidationLabel.FontColorOverride = Color.Red;
        ValidationLabel.Visible = false;

        // Style the content panel
        var styleBox = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#20252b"),
            BorderColor = Color.FromHex("#3e4650"),
            BorderThickness = new Thickness(1)
        };

        ContentPanel.PanelOverride = styleBox;

        SetupEventHandlers();
    }

    private void SetupEventHandlers()
    {
        TitleEdit.OnTextChanged += args =>
        {
            if (args.Text.Length > CharacterDossier.ShortTextLength)
            {
                TitleEdit.Text = args.Text[..CharacterDossier.ShortTextLength];
            }
            ValidateFields();
        };

        InvolvedEdit.OnTextChanged += args =>
        {
            if (args.Text.Length > CharacterDossier.ShortTextLength)
            {
                InvolvedEdit.Text = args.Text[..CharacterDossier.ShortTextLength];
            }
            ValidateFields();
        };

        DescriptionEdit.OnTextChanged += _ => ValidateFields();

        SaveButton.OnPressed += _ =>
        {
            if (!_isValid)
                return;
            Close();
        };

        DescriptionEdit.Placeholder =
            new Rope.Leaf(Loc.GetString("character-dossier-entry-edit-popup-description-placeholder"));

        TitleEdit.PlaceHolder = Loc.GetString("character-dossier-entry-edit-popup-title-placeholder");
        InvolvedEdit.PlaceHolder = Loc.GetString("character-dossier-entry-edit-popup-involved-placeholder");
    }

    private void ValidateFields()
    {
        var descriptionText = Rope.Collapse(DescriptionEdit.TextRope);
        var descriptionLength = descriptionText.Length;

        string? error = null;
        (string, object)[]? parameters = null;
        if (string.IsNullOrWhiteSpace(TitleEdit.Text))
        {
            error = "character-dossier-entry-edit-popup-title-required";
        }
        else if (string.IsNullOrWhiteSpace(InvolvedEdit.Text))
        {
            error = "character-dossier-entry-edit-popup-involved-required";
        }
        else if (string.IsNullOrWhiteSpace(descriptionText))
        {
            error = "character-dossier-entry-edit-popup-description-required";
        }
        else if (descriptionLength > CharacterDossier.LongTextLength)
        {
            error = "character-dossier-entry-edit-popup-description-too-long";
            parameters =
            [
                ("current", descriptionLength),
                ("max", CharacterDossier.LongTextLength),
            ];
        }

        _isValid = error == null;
        ValidationLabel.Visible = !_isValid;
        if (error != null)
            ValidationLabel.Text = parameters == null ? Loc.GetString(error) : Loc.GetString(error, parameters);

        SaveButton.Disabled = !_isValid;
    }

    public DossierEntry GetContents()
    {
        var desc = Rope.Collapse(DescriptionEdit.TextRope).Trim();
        return new DossierEntry(
            TitleEdit.Text.Trim(),
            InvolvedEdit.Text.Trim(),
            desc);
    }

    public void SetContents(DossierEntry entry)
    {
        TitleEdit.Text = entry.Title;
        InvolvedEdit.Text = entry.Involved;
        DescriptionEdit.TextRope = new Rope.Leaf(entry.Description);
        ValidateFields();
    }
}
