using System.Diagnostics.CodeAnalysis;
using System.Linq;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared._RedStar.Genetics.Prototypes;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._RedStar.Guidebook.Controls;

[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuideGeneticMutationEmbed : PanelContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideGeneticMutationEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideGeneticMutationEmbed(GeneticMutationPrototype recipe) : this()
    {
        GenerateControl(recipe);
    }

    public bool CheckMatchesSearch(string query) => this.ChildrenContainText(query);

    public void SetHiddenState(bool state, string query) => Visible = CheckMatchesSearch(query) ? state : !state;

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Recipe", out var id) || !_prototypes.TryIndex<GeneticMutationPrototype>(id, out var recipe))
        {
            Logger.GetSawmill("guidebook.genetics").Error("GuideGeneticMutationEmbed requires a valid Recipe prototype.");
            return false;
        }

        GenerateControl(recipe);
        control = this;
        return true;
    }

    private void GenerateControl(GeneticMutationPrototype recipe)
    {
        var result = _prototypes.Index(recipe.ResultGene);
        RepresentedPrototype = result;
        ResultName.SetMarkup($"[bold]{Loc.GetString($"gene-{result.ID}-name")}[/bold]");
        TierLabel.Text = Loc.GetString("guidebook-genetic-mutation-tier", ("tier", result.Tier));
        DurationLabel.Text = Loc.GetString("guidebook-genetic-mutation-duration", ("seconds", Math.Round(recipe.Duration.TotalSeconds, 2)));
        ChanceLabel.Text = Loc.GetString("guidebook-genetic-mutation-chance", ("chance", MathF.Round(recipe.Chance * 100, 2)));

        Genes.RemoveAllChildren();
        foreach (var id in recipe.RequiredGenes.OrderBy(id => Loc.GetString($"gene-{id}-name")))
        {
            Genes.AddChild(PrototypeLink(_prototypes.Index(id), Loc.GetString($"gene-{id}-name")));
        }

        Reagents.RemoveAllChildren();
        foreach (var (id, amount) in recipe.RequiredReagents.OrderBy(entry => _prototypes.Index(entry.Key).LocalizedName))
        {
            var reagent = _prototypes.Index(id);
            Reagents.AddChild(PrototypeLink(reagent, reagent.LocalizedName));
            Reagents.AddChild(new Label
            {
                Text = Loc.GetString("guidebook-genetic-mutation-amount", ("amount", amount)),
                HorizontalAlignment = HAlignment.Right,
                Margin = new Thickness(12, 0, 0, 0),
            });
        }
    }

    private static GuidebookRichPrototypeLink PrototypeLink(IPrototype prototype, string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        var link = new GuidebookRichPrototypeLink { LinkedPrototype = prototype };
        link.SetMessage(message);
        return link;
    }
}
