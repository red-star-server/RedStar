using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._RedStar.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class PointDiskPrintControl : PanelContainer
{
    private readonly EntProtoId _disk;

    public event Action<EntProtoId>? OnPrint;

    public PointDiskPrintControl(EntProtoId disk)
    {
        RobustXamlLoader.Load(this);
        _disk = disk;
        PrintButton.OnPressed += _ => OnPrint?.Invoke(_disk);
    }

    public void UpdateState(int points, bool canPrint)
    {
        PointsLabel.Text = Loc.GetString("point-disk-console-points", ("points", points));
        PrintButton.Disabled = !canPrint;
    }
}
