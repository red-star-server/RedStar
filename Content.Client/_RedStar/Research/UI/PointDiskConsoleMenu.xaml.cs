using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RedStar.Research;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._RedStar.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class PointDiskConsoleMenu : FancyWindow
{
    private readonly Dictionary<EntProtoId, PointDiskPrintControl> _rows = new();

    public event Action? OnServerSelected;
    public event Action<EntProtoId>? OnPrint;

    public PointDiskConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        ServerButton.OnPressed += _ => OnServerSelected?.Invoke();
    }

    public void UpdateState(PointDiskConsoleState state)
    {
        BalanceLabel.Text = Loc.GetString("point-disk-console-points", ("points", state.Points));
        var status = !state.Powered ? "no-power"
            : state.Printing ? "printing"
            : !state.Connected ? "no-server"
            : null;
        StatusLabel.Visible = status != null;
        StatusLabel.Text = status == null ? string.Empty : Loc.GetString($"point-disk-console-status-{status}");

        // Keep controls stable as the connected server updates its balance.
        var rebuild = _rows.Count != state.Disks.Count;
        foreach (var disk in _rows.Keys)
        {
            if (state.Disks.ContainsKey(disk))
                continue;

            rebuild = true;
            break;
        }

        if (rebuild)
        {
            foreach (var row in _rows.Values)
            {
                row.OnPrint -= OnPrintPressed;
                DiskList.RemoveChild(row);
            }

            _rows.Clear();
            foreach (var (disk, _) in state.Disks.OrderBy(static entry => entry.Value))
            {
                var row = new PointDiskPrintControl(disk);
                row.OnPrint += OnPrintPressed;
                DiskList.AddChild(row);
                _rows.Add(disk, row);
            }
        }

        foreach (var (disk, row) in _rows)
        {
            var points = state.Disks[disk];
            row.UpdateState(points, state.Powered && state.Connected && !state.Printing && state.Points >= points);
        }
    }

    private void OnPrintPressed(EntProtoId disk)
    {
        OnPrint?.Invoke(disk);
    }
}
