using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes; // RS14

namespace Content.Client.HealthAnalyzer.UI;

[GenerateTypedNameReferences]
public sealed partial class HealthAnalyzerWindow : FancyWindow
{
    // RS14-start
    public event Action<MedicalTriagePriority>? OnPriorityChanged;
    public event Action? OnClaim;
    private readonly IEntityManager _entities;
    private readonly IPlayerManager _players;
    private readonly AccessReaderSystem _access;
    // RS14-end

    public HealthAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        // RS14-start
        _entities = IoCManager.Resolve<IEntityManager>();
        _players = IoCManager.Resolve<IPlayerManager>();
        _access = _entities.System<AccessReaderSystem>();
        foreach (var priority in Enum.GetValues<MedicalTriagePriority>())
        {
            PriorityOptionButton.AddItem(Loc.GetString($"medical-triage-{priority.ToString().ToLowerInvariant()}"), (int) priority);
        }

        PriorityOptionButton.OnItemSelected += args => OnPriorityChanged?.Invoke((MedicalTriagePriority) args.Id);
        ClaimButton.OnPressed += _ => OnClaim?.Invoke();
        // RS14-end
    }

    public void Populate(HealthAnalyzerUiState state)
    {
        HealthAnalyzer.Populate(state);
        // RS14-start
        var patient = _entities.GetEntity(state.TargetEntity);
        TriageControls.Visible = patient != null && state.ScanMode &&
                                 _players.LocalEntity is { } actor &&
                                 _access.FindAccessTags(actor).Contains(new ProtoId<AccessLevelPrototype>("Medical"));
        if (!TriageControls.Visible) return;
        _entities.TryGetComponent<MedicalTriageStatusComponent>(patient!.Value, out var triage);
        PriorityOptionButton.SelectId((int) (triage?.Priority ?? MedicalTriagePriority.None));
        DoctorLabel.Text = Loc.GetString("medical-triage-doctor", ("doctor",
            triage?.DoctorName ?? Loc.GetString("medical-triage-unassigned")));
        ClaimButton.Text = triage?.DoctorName == null
            ? Loc.GetString("medical-triage-claim")
            : Loc.GetString("medical-triage-toggle-claim");
        // RS14-end
    }
}
